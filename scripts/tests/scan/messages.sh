#!/usr/bin/env bash
# Attribution in messages: the commit-msg hook and the range scan apply one rule.
source "$(dirname "$0")/common.sh"

# Attribution. Each message goes to the commit-msg hook; the same messages, one commit
# each and made with the hook bypassed, go to the range scan as CI runs it.
bad_messages="$tmp/bad"
good_messages="$tmp/good"
mkdir "$bad_messages" "$good_messages"
m=0
bad() { # <expected text> <message>
  m=$((m + 1))
  printf '%s\n' "$2" >"$bad_messages/$m.message"
  printf '%s\n' "$1" >"$bad_messages/$m.says"
}
good() { # <message>
  m=$((m + 1))
  printf '%s\n' "$1" >"$good_messages/$m.message"
}
body="feat: a thing

It does a thing.
"
bad "$has_credit" "$body
$credit: $N <noreply@example.com>"
bad "$has_credit" "$body
$(printf '%s' "$credit" | tr 'A-Z' 'a-z'): $N <noreply@example.com>"
bad "$has_credit" "$body
$(printf '%s' "$credit" | tr 'a-z' 'A-Z'): $N <noreply@example.com>"
bad "$has_credit" "$body
  $credit: $N <noreply@example.com>"
bad "$has_credit" "$body
	$credit: $N <noreply@example.com>"
bad "$has_credit" "$body
> $credit: $N <noreply@example.com>"
bad "$has_credit" "$body
$credit: Jane Human <jane@example.com>"
bad "$credits_agent" "$body
This was Generated ""with $N Code"
bad "$credits_agent" "$body
Generated ""by ${N}"
bad "$credits_agent" "$body
Generated ""with [Some Tool](https://example.com/tool)"
bad "$credits_agent" "$body
generated ""by a tool, see https://${N}.example.com/code"
bad "$credits_agent" "$body
Signed-off-by: $N <noreply@example.com>"
bad "$credits_agent" "$body
Signed-off-by: Mark via $N <m@example.com>"
bad "$credits_agent" "$body
Assisted-by: ${N}Code"
bad "$credits_agent" "$body
Co-developed-by: Open""AI Cod""ex <noreply@example.com>"
bad "$credits_agent" "$body
Reviewed-by: An""thropic Op""us <noreply@example.com>"
good "fix: the hook refuses a $credit line"
good "$body
Generated by the build script, this file is checked in."
good "$body
The report is generated with care by the timing script."
good "$body
Reviewed-by: Jane Human <jane@example.com>
Signed-off-by: Op""us Jones <jones@example.com>"

for f in "$bad_messages"/*.message; do
  expect_fail "the commit-msg hook: $f" "$(cat "${f%.message}.says")" scripts/hooks/commit-msg "$f"
done
for f in "$good_messages"/*.message; do
  expect_pass "the commit-msg hook: $f" scripts/hooks/commit-msg "$f"
done
# What `git commit -v` adds below its scissors line is not the message.
printf 'feat: a thing\n# ------------------------ >8 ------------------------\n %s: x\n' "$credit" >"$tmp/message"
expect_pass "the commit-msg hook, a diff under the scissors line" scripts/hooks/commit-msg "$tmp/message"

fresh bad-messages
for f in "$bad_messages"/*.message; do
  echo "$f" >thing.txt
  git add thing.txt
  git commit -q --no-verify -F "$f"
  git rev-parse HEAD >"${f%.message}.sha"
done
expect_fail "messages with attribution, as CI runs it" "attribution check:" \
  env -u WHIZBANG_WORDLIST "$scan" --secrets-only --range "$first" HEAD
for f in "$bad_messages"/*.message; do
  says "commit $(cat "${f%.message}.sha"): $(cat "${f%.message}.says")"
done
expect_fail "messages with attribution, pushed" "$has_credit" git push origin bad-messages
not_on_remote refs/heads/bad-messages
fresh good-messages
for f in "$good_messages"/*.message; do
  echo "$f" >thing.txt
  git add thing.txt
  git commit -q --no-verify -F "$f"
done
expect_pass "messages without attribution" env -u WHIZBANG_WORDLIST "$scan" --secrets-only --range "$first" HEAD
