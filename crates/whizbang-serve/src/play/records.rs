/// The file at this path under the folder, when the list holds one: its type and bytes.
pub fn find(path: &str) -> Option<(&'static str, &'static [u8])> {
    FILES
        .iter()
        .find(|(named, _, _)| *named == path)
        .map(|(_, content_type, bytes)| (*content_type, *bytes))
}

/// The paths of every file the list holds.
pub fn paths() -> impl Iterator<Item = &'static str> {
    FILES.iter().map(|(path, _, _)| *path)
}

/// The names of the records: each `<name>.md`, without its `.md`.
pub fn names() -> impl Iterator<Item = &'static str> {
    paths().filter_map(|path| path.strip_suffix(".md"))
}
