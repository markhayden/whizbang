//! The tool records, `docs/reference/tools/`, embedded in the binary (`SPEC.md` section 8:
//! "the playground shows the same page"; plan m5, task W3, item 7): each record's
//! Markdown and its example images, served by `GET /api/records/{name}` and its files.
//! The list is fixed, as the interface's is ([`super::assets`]): a test fails on a file
//! of the folder that this list does not hold, or the reverse
//! (`play::the_embedded_records_are_the_reference_folder`), and names each, so a record
//! written again by `scripts/tool-record.sh` or `just docs` is listed here in the same
//! change. Nothing outside the list is ever read.

/// One file: its path under the folder, its type, and its bytes.
type File = (&'static str, &'static str, &'static [u8]);

macro_rules! record {
    ($path:literal, $type:literal) => {
        (
            $path,
            $type,
            include_bytes!(concat!("../../../../docs/reference/tools/", $path)),
        )
    };
}

